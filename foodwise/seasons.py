# نوع اليوم الذي يتعلمه نموذج التوقع: عادي، رمضان، عيد، إجازة
DAY_TYPES = {0: "عادي", 1: "رمضان", 2: "عيد", 3: "إجازة"}
_TYPE_OF = {"رمضان": 1, "العشر الأواخر من رمضان": 1, "عيد الفطر": 2, "عيد الأضحى": 2}


def day_type(d: pd.Timestamp) -> int:
    """العيد أولًا، ثم رمضان، ثم الإجازات (المدرسية واليوم الوطني ويوم التأسيس)."""
    hit = [_TYPE_OF.get(e.name, 3) for e in _EVENTS.itertuples() if e.start <= d <= e.end]
    if not hit:
        return 0
    return 2 if 2 in hit else (1 if 1 in hit else 3)


def events() -> pd.DataFrame:
    df = pd.DataFrame(EVENTS, columns=["name", "start", "end"])
    df["start"], df["end"] = pd.to_datetime(df.start), pd.to_datetime(df.end)
    return df


def _when(n: int) -> str:
    return {0: "اليوم", 1: "غدًا", 2: "بعد يومين"}.get(n, f"بعد {n} أيام")


def upcoming(t: pd.Timestamp, days: int = NOTICE_DAYS) -> list[str]:
    """المواسم الجارية اليوم أو التي تبدأ خلال أسبوع، بنص قصير يظهر بجانب يوم الراتب."""
    out = []
    for e in events().sort_values("start").itertuples():
        if e.start <= t <= e.end:
            out.append(f"{e.name}: اليوم" if e.start == e.end else f"{e.name}: حتى {e.end.day} {_MONTHS[e.end.month - 1]}")
        elif 0 < (e.start - t).days <= days:
            out.append(f"{_when((e.start - t).days)}: {e.name}")
    return out


_EVENTS = events()

